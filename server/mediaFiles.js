import fs from 'node:fs';
import path from 'node:path';
import { PROJECTS_DIR } from './config.js';
import { store } from './db.js';
import { validateDatabase } from './store.js';

function addSurfaceFiles(surface, files) {
  if (!surface) return;
  for (const name of [surface.file, surface.proxy, surface.poster, surface.compatibilityPreview?.file, surface.mobilePreview?.file]) {
    if (name) files.add(path.basename(name));
  }
  if (surface.file && surface.status === 'processing') {
    const base = path.parse(surface.file).name;
    files.add(`${base}.preview.mp4`);
    files.add(`${base}.poster.jpg`);
    files.add(`${base}.compat.mp4`);
    files.add(`${base}.mobile.mp4`);
  }
  addSurfaceFiles(surface.replacement, files);
}

// Retain files referenced by the rollback snapshot as well as the live database.
export function cleanupProjectFiles(projectId) {
  let backup;
  try { backup = validateDatabase(JSON.parse(fs.readFileSync(store.backup, 'utf8'))); }
  catch (error) { if (error.code !== 'ENOENT') return; }
  const projects = [store.project(projectId), backup?.projects.find((p) => p.id === projectId)].filter(Boolean);
  const dir = path.join(PROJECTS_DIR, projectId);
  if (!projects.length) {
    try { fs.rmSync(dir, { recursive: true, force: true }); }
    catch (error) { console.warn('[cleanup]', error.message); }
    return;
  }
  const files = new Set();
  for (const project of projects) {
    for (const surface of Object.values(project.surfaces || {})) addSurfaceFiles(surface, files);
    for (const surface of Object.values(project.publishedVideoScene?.surfaces || {})) addSurfaceFiles(surface, files);
    for (const scene of project.videoScenes || []) {
      for (const surface of Object.values(scene.surfaces || {})) addSurfaceFiles(surface, files);
      for (const surface of Object.values(scene.published?.surfaces || {})) addSurfaceFiles(surface, files);
    }
    for (const asset of project.sceneAssets || []) if (asset.file) files.add(path.basename(asset.file));
  }
  let names;
  try { names = fs.readdirSync(dir); } catch { return; }
  for (const name of names) {
    // Only sweep files generated by HALL/5; keep both current and rollback assets.
    if (files.has(name) || !/^(?:(?:(?:right|back|left|center|floor)-[a-z0-9_-]+|demo-(?:right|back|left|center|floor))\.(?:mp4|m4v|mov|webm|mkv|avi|mts|m2ts|ts|mpg|mpeg|preview\.mp4|compat\.mp4|mobile\.mp4|poster\.jpg)|model-[a-z0-9_-]+\.glb)$/i.test(name)) continue;
    try { fs.rmSync(path.join(dir, name), { force: true }); }
    catch (error) { console.warn('[cleanup]', error.message); }
  }
}

export function cleanupOrphanedMedia() {
  for (const entry of fs.readdirSync(PROJECTS_DIR, { withFileTypes: true })) {
    if (entry.isDirectory() && /^[a-z0-9_-]+$/i.test(entry.name)) cleanupProjectFiles(entry.name);
  }
}
